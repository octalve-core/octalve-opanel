test('website releases rollback and backup restore preserve practice state',async({page})=>{
 await page.goto('/practice/');
 await page.getByLabel('Domain name',{exact:true}).fill('site.test');
 await page.getByRole('button',{name:'Add domain',exact:true}).click();
 await expect(page.getByRole('cell',{name:'site.test',exact:true})).toBeVisible();
 await page.getByRole('link',{name:'Websites',exact:true}).click();
 await page.getByLabel('Domain',{exact:true}).selectOption('site.test');
 await page.getByLabel('Website name').fill('My website');
 await page.getByRole('button',{name:'Add website',exact:true}).click();
 for(const label of ['First','Second']){
  await page.getByRole('button',{name:'New release'}).click();
  await page.getByLabel('Release label').fill(label);
  await page.getByRole('button',{name:'Save simulated release'}).click();
  await expect(page.getByText(`current release: ${label}`)).toBeVisible();
 }
 await page.getByRole('button',{name:'Roll back'}).click();
 await page.getByRole('button',{name:'Confirm action'}).click();
 await expect(page.getByText('current release: First')).toBeVisible();
 await page.getByRole('link',{name:'Backups',exact:true}).click();
 await page.getByLabel('Backup name').fill('Checkpoint');
 await page.getByRole('button',{name:'Add backup',exact:true}).click();
 await page.getByRole('button',{name:'Restore',exact:true}).click();
 await page.getByRole('button',{name:'Confirm action'}).click();
 await page.getByRole('link',{name:'Websites',exact:true}).click();
 await expect(page.getByText('current release: First')).toBeVisible();
});
test('file editing and deletion require real state updates and confirmation',async({page})=>{
 await page.goto('/practice/files/');
 await page.getByLabel('Relative path').fill('note.txt');
 await page.getByLabel('Text content (up to 4 KB)').fill('Hello');
 await page.getByRole('button',{name:'Add file or folder',exact:true}).click();
 await page.getByRole('button',{name:'Edit',exact:true}).click();
 await page.getByRole('dialog').getByLabel('Text content (up to 4 KB)').fill('Updated');
 await page.getByRole('button',{name:'Save changes',exact:true}).click();
 await expect(page.getByText('size bytes: 7')).toBeVisible();
 await page.getByRole('button',{name:'Delete',exact:true}).click();
 await page.getByRole('button',{name:'Cancel',exact:true}).click();
 await expect(page.getByRole('cell',{name:'note.txt',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Delete',exact:true}).click();
 await page.getByRole('button',{name:'Confirm action'}).click();
 await expect(page.getByRole('cell',{name:'note.txt',exact:true})).toHaveCount(0);
});
test('DNS editor remains usable on a short phone screen',async({page})=>{
 await page.setViewportSize({width:360,height:640});
 await page.goto('/practice/');
 await page.getByLabel('Domain name',{exact:true}).fill('mobile.test');
 await page.getByRole('button',{name:'Add domain',exact:true}).click();
 await expect(page.getByRole('cell',{name:'mobile.test',exact:true})).toBeVisible();
 await page.getByRole('link',{name:'DNS records',exact:true}).click();
 await page.getByLabel('Domain',{exact:true}).selectOption('mobile.test');
 await page.getByLabel('Record name').fill('www');
 await page.getByLabel('Value',{exact:true}).fill('192.0.2.1');
 await page.getByRole('button',{name:'Add DNS record'}).click();
 await page.getByRole('button',{name:'Edit',exact:true}).click();
 const dialog=page.getByRole('dialog');
 await dialog.getByLabel('Value',{exact:true}).fill('192.0.2.2');
 await dialog.getByRole('button',{name:'Save changes'}).scrollIntoViewIfNeeded();
 await expect(dialog.getByRole('button',{name:'Save changes'})).toBeInViewport();
 await dialog.getByRole('button',{name:'Save changes'}).click();
 await expect(dialog).toHaveCount(0);
 await expect(page.getByText('192.0.2.2',{exact:false})).toBeVisible();
});

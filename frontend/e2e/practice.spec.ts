import {test,expect} from '@playwright/test';
test('practice domain DNS SSL and restore use persisted isolated API',async({page})=>{
 await page.goto('/practice/');
 await expect(page.getByText('Local simulation', {exact:true})).toBeVisible();
 await page.getByLabel('Domain name',{exact:true}).fill('example.test');
 await page.getByRole('button',{name:'Add domain',exact:true}).click();
 await expect(page.getByRole('cell',{name:'example.test',exact:true})).toBeVisible();
 await page.getByRole('link',{name:'DNS records',exact:true}).click();
 await page.getByLabel('Domain',{exact:true}).selectOption('example.test');
 await page.getByLabel('Record name').fill('www');
 await page.getByLabel('Value',{exact:true}).fill('192.0.2.1');
 await page.getByRole('button',{name:'Add DNS record'}).click();
 await expect(page.getByText('192.0.2.1',{exact:false})).toBeVisible();
 await page.getByRole('link',{name:'SSL certificates',exact:true}).click();
 await expect(page.getByRole('heading',{name:'SSL certificates',exact:true})).toBeVisible();
 await page.getByLabel('Domain',{exact:true}).selectOption('example.test');
 await page.getByRole('button',{name:'Request certificate'}).click();
 await page.getByRole('button',{name:'Simulate validation'}).click();
 await expect(page.getByText('simulation-valid',{exact:false})).toBeVisible();
 await page.reload();
 await expect(page.getByText('simulation-valid',{exact:false})).toBeVisible();
});
